"""Build the offline Three.js photo bundle; source photography is never modified.

Run: python tools/build_showcase_assets.py [--check]
Only assets/showcase/products.js is generated. No site build or dependencies.
Matting is opt-in per photograph; omit `matte` for lifestyle/unknown backgrounds.
"""
from __future__ import annotations

import argparse
import base64
import json
from pathlib import Path
from html.parser import HTMLParser

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data/showcase-products.json"
OUTPUT = ROOT / "assets/showcase/products.js"
MIME = {".webp": "image/webp", ".png": "image/png", ".jpg": "image/jpeg", ".jpeg": "image/jpeg"}


class Anchors(HTMLParser):
    def __init__(self, text):
        super().__init__()
        self.ids = set()
        self.feed(text)

    def handle_starttag(self, tag, attrs):
        self.ids.update(value for key, value in attrs if key == "id")


def bundle():
    items = json.loads(SOURCE.read_text(encoding="utf-8"))
    if not isinstance(items, list) or not items:
        raise ValueError("The showcase needs product records.")
    seen, anchors, output = set(), {}, []
    for item in items:
        for key in ("id", "lane", "name", "subtitle", "src", "href"):
            if not isinstance(item.get(key), str) or not item[key].strip():
                raise ValueError(f"Missing {key}: {item.get('id', '(unnamed)')}")
        if item["id"] in seen or item["lane"] not in ("storage", "kitchen"):
            raise ValueError(f"Duplicate ID or unknown lane: {item['id']}")
        seen.add(item["id"])
        if item.get("matte", "preserve") not in ("edge-white", "preserve"):
            raise ValueError(f"Unknown matte mode: {item['id']}")
        photo = (ROOT / item["src"]).resolve()
        if not photo.is_relative_to(ROOT / "assets") or not photo.is_file() or photo.suffix.lower() not in MIME:
            raise ValueError(f"Not a local product photograph: {item['src']}")
        if any(word in photo.stem.lower() for word in ("dimension", "specification", "size-table")):
            raise ValueError(f"Use a product photograph, not a dimension sheet: {item['src']}")
        page, separator, anchor = item["href"].partition("#")
        target = (ROOT / page).resolve()
        if not separator or not anchor or target.parent != ROOT or target.suffix != ".html" or not target.is_file():
            raise ValueError(f"Not a local product-page anchor: {item['href']}")
        if page not in anchors:
            anchors[page] = Anchors(target.read_text(encoding="utf-8")).ids
        if anchor not in anchors[page]:
            raise ValueError(f"Missing destination anchor: {item['href']}")
        encoded = base64.b64encode(photo.read_bytes()).decode("ascii")
        output.append({**item, "texture": f"data:{MIME[photo.suffix.lower()]};base64,{encoded}"})
    if {item["lane"] for item in items} != {"storage", "kitchen"}:
        raise ValueError("Both product lanes must contain photographs.")
    return "/* Generated by tools/build_showcase_assets.py; real, unmodified product photographs. */\nwindow.MAYLENDY_SHOWCASE_PRODUCTS = " + json.dumps(output, ensure_ascii=False, indent=2) + ";\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Validate sources, links and the current bundle without writing.")
    args = parser.parse_args()
    content = bundle()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != content:
            parser.exit(1, "Showcase bundle is stale; run tools/build_showcase_assets.py.\n")
        print("Showcase bundle is current; all source photographs and product anchors are valid.")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(content, encoding="utf-8", newline="\n")
        print(f"Built {OUTPUT.relative_to(ROOT)} ({len(content.encode('utf-8')):,} bytes).")


if __name__ == "__main__":
    main()
